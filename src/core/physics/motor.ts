/**
 * DC Motor Dynamic Model
 * Simulates electrical armature circuit, Back-EMF, torque saturation,
 * gearbox efficiency, and friction.
 */

import type { MotorConfig, FrictionConfig } from './types.ts';

export class DCMotor {
  private config: MotorConfig;
  private friction: FrictionConfig;

  constructor(config: MotorConfig, friction: FrictionConfig) {
    this.config = { ...config };
    this.friction = { ...friction };
  }

  public updateConfig(config: Partial<MotorConfig>, friction?: Partial<FrictionConfig>): void {
    Object.assign(this.config, config);
    if (friction) Object.assign(this.friction, friction);
  }

  public getConfig(): Readonly<MotorConfig> {
    return this.config;
  }

  public getFriction(): Readonly<FrictionConfig> {
    return this.friction;
  }

  /**
   * Computes electromagnetic torque generated by the motor given an applied control voltage (V)
   * and the current angular velocity of the arm (omega, rad/s).
   * 
   * Equations:
   * V_clamped = clamp(V, -V_max, V_max)
   * V_bemf = Kb * omega * gearRatio
   * I_a = (V_clamped - V_bemf) / R
   * tau_raw = Kt * I_a * gearRatio * efficiency
   * tau_sat = clamp(tau_raw, -tau_max, tau_max)
   */
  public computeTorque(voltage: number, omega: number): number {
    const { resistance, torqueConstant, backEmfConstant, maxVoltage, maxTorque, gearRatio, efficiency } = this.config;
    
    // Clamp applied voltage within motor driver supply rails
    const vClamped = Math.max(-maxVoltage, Math.min(maxVoltage, voltage));

    // Motor shaft velocity considering gear ratio
    const omegaMotor = omega * gearRatio;

    // Back-Electromotive Force generated by magnetic flux
    const vBemf = backEmfConstant * omegaMotor;

    // Armature current (Ohm's Law across armature resistance)
    const current = (vClamped - vBemf) / Math.max(resistance, 1e-4);

    // Raw electro-mechanical output torque
    const tauRaw = torqueConstant * current * gearRatio * efficiency;

    // Torque saturation due to magnetic core saturation and current limits
    return Math.max(-maxTorque, Math.min(maxTorque, tauRaw));
  }

  /**
   * Computes friction torque on an axis given angular velocity omega.
   * Includes both viscous damping (-b * omega) and Coulomb dry friction (-c * sgn(omega)).
   */
  public computeFriction(omega: number, viscousCoeff: number, coulombCoeff: number): number {
    const tauViscous = -viscousCoeff * omega;
    // Smooth Coulomb approximation near zero to avoid discontinuity chattering: tanh(omega / epsilon)
    const eps = 0.02;
    const tauCoulomb = -coulombCoeff * Math.tanh(omega / eps);
    return tauViscous + tauCoulomb;
  }
}
